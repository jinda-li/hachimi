"""玩具零件：几种猫喜欢的单一机制。拼一个小游戏只要几行：

    import 零件
    start, step, draw, over = 零件.躲避(标题="滑雪", 主角="A", 障碍="^", 宝贝="*", 撞了="栽进雪堆！")

每个零件返回 start, step, draw, over 四个函数，跟自己从头写的游戏一样用。
参数都有默认值，只改想改的。符号最好是一个字符宽的（A ^ * o @ # ~ 这种）；
用汉字或 emoji 也行，格子会自动变宽，场地就窄一半。

  躲避   东西从下面迎面冲上来，左右躲开，捡宝贝。滑雪、过马路、游泳躲鲨鱼
  接住   东西从上面掉下来，左右挪着接。接雪花、接小鱼、接罐罐
  扑     一个猎物在乱跑，追过去，按空格扑。激光点、蝴蝶、老鼠
  打地鼠 洞里冒出东西，挪到那个洞，按空格拍。地鼠、鼹鼠、从纸箱探头的猫
  跳     往前跑，按空格或上跳过障碍。跑酷、跳水坑、跳栏杆
"""
import random
import unicodedata


def _宽(s):
    return 2 if any(unicodedata.east_asian_width(c) in "WF" or ord(c) >= 0x1F000 for c in s) else 1


def _一(s):
    """一格放一个符号：多给的字只要第一个。"""
    return str(s)[:1] or "?"


def _格(c, w):
    if not c:
        return " " * w
    return c if _宽(c) == w else c + " " * (w - _宽(c))


def _框(标题, 行们, 宽, w, 底下):
    """画一个带边的场地。行们是一行一行的格子（每格是一个符号或空字符串）。"""
    lines = [f" {标题}"[:40], "+" + "-" * (宽 * w) + "+"]
    lines += ["|" + "".join(_格(c, w) for c in row) + "|" for row in 行们]
    lines += ["+" + "-" * (宽 * w) + "+", 底下]
    return "\n".join(lines)


def _说(s, 话, 多久=6):
    s["话"], s["话还剩"] = 话, 多久


def _底下(s, 文字):
    if s.get("话还剩", 0) > 0:
        s["话还剩"] -= 1
        return f" {文字}  {s['话']}"
    return f" {文字}"


def _场地(宽, 高, w, 最高=16):
    return max(6, min(宽, 38 // w)), max(4, min(高, 最高))


# ── 躲避 ──────────────────────────────────────────────

def 躲避(标题="躲避", 主角="A", 障碍="^", 宝贝="*", 宽=20, 高=14, 障碍多少=0.08, 宝贝多少=0.03, 命=3,
       终点=300, 分数叫="走了", 宝贝叫="捡到", 撞了="撞到了！", 捡到了="捡到了！", 结束="到了！"):
    主角, 障碍, 宝贝 = _一(主角), _一(障碍), _一(宝贝)
    w = max(_宽(主角), _宽(障碍), _宽(宝贝))
    宽, 高 = _场地(宽, 高, w)

    def 新的一行():
        row = []
        for _ in range(宽):
            r = random.random()
            row.append(障碍 if r < 障碍多少 else 宝贝 if r < 障碍多少 + 宝贝多少 else "")
        return row

    def start():
        return {"格": [[""] * 宽 for _ in range(高 // 2)] + [新的一行() for _ in range(高 - 高 // 2)],
                "x": 宽 // 2, "命": 命, "走": 0, "宝": 0, "到了": False}

    def step(s, 键):
        if 键 == "左":
            s["x"] = max(0, s["x"] - 1)
        elif 键 == "右":
            s["x"] = min(宽 - 1, s["x"] + 1)
        s["格"] = s["格"][1:] + [新的一行()]
        s["走"] += 1
        c = s["格"][1][s["x"]]
        if c == 障碍:
            s["命"] -= 1
            _说(s, 撞了)
        elif c == 宝贝:
            s["宝"] += 1
            _说(s, 捡到了)
        s["格"][1][s["x"]] = ""
        if 终点 and s["走"] >= 终点:
            s["到了"] = True
            _说(s, 结束, 99)
        return s

    def draw(s):
        行们 = [list(r) for r in s["格"]]
        行们[1][s["x"]] = 主角
        return _框(标题, 行们, 宽, w, _底下(s, f"{分数叫} {s['走']}  {宝贝叫} {s['宝']}  命 {s['命']}"))

    def over(s):
        return s["命"] <= 0 or s["到了"]

    return start, step, draw, over


# ── 接住 ──────────────────────────────────────────────

def 接住(标题="接住", 主角="\\_/", 好东西="*", 坏东西="x", 宽=20, 高=14, 掉多少=0.3, 坏的多少=0.2, 命=3,
       时长=300, 分数叫="接到", 接到了="接到了！", 接错了="哎呀！", 结束="接够了"):
    好东西, 坏东西, 篮子 = _一(好东西), _一(坏东西), list(str(主角)[:5] or "U")  # 主角几个字就占几格
    w = max(_宽(好东西), _宽(坏东西), _宽(主角))
    宽, 高 = _场地(宽, 高, w)

    def start():
        return {"x": (宽 - len(篮子)) // 2, "掉": [], "接": 0, "命": 命, "时间": 0}

    def step(s, 键):
        if 键 == "左":
            s["x"] = max(0, s["x"] - 1)
        elif 键 == "右":
            s["x"] = min(宽 - len(篮子), s["x"] + 1)
        s["时间"] += 1
        留下 = []
        for y, x, 是 in s["掉"]:
            y += 1
            if y == 高 - 1 and s["x"] <= x < s["x"] + len(篮子):
                if 是 == 好东西:
                    s["接"] += 1
                    _说(s, 接到了)
                else:
                    s["命"] -= 1
                    _说(s, 接错了)
            elif y < 高:
                留下.append((y, x, 是))
        if random.random() < 掉多少:
            留下.append((0, random.randrange(宽), 坏东西 if random.random() < 坏的多少 else 好东西))
        s["掉"] = 留下
        if s["时间"] >= 时长:
            _说(s, 结束, 99)
        return s

    def draw(s):
        行们 = [[""] * 宽 for _ in range(高)]
        for y, x, 是 in s["掉"]:
            行们[y][x] = 是
        for i, c in enumerate(篮子):
            行们[高 - 1][s["x"] + i] = c
        return _框(标题, 行们, 宽, w, _底下(s, f"{分数叫} {s['接']}  命 {s['命']}  还剩 {max(0, 时长 - s['时间'])}"))

    def over(s):
        return s["命"] <= 0 or s["时间"] >= 时长

    return start, step, draw, over


# ── 扑 ────────────────────────────────────────────────

def 扑(标题="扑", 主角="@", 猎物="o", 宽=24, 高=12, 猎物多快=0.6, 时长=300,
      分数叫="扑到", 扑到了="扑到了！", 扑空了="扑空了……", 结束="累了"):
    主角, 猎物 = _一(主角), _一(猎物)
    w = max(_宽(主角), _宽(猎物))
    宽, 高 = _场地(宽, 高, w)

    def 随便哪():
        return random.randrange(宽), random.randrange(高)

    def start():
        x, y = 随便哪()
        return {"我": [宽 // 2, 高 // 2], "它": [x, y], "扑到": 0, "扑空": 0, "时间": 0}

    def step(s, 键):
        我, 它 = s["我"], s["它"]
        dx, dy = {"左": (-1, 0), "右": (1, 0), "上": (0, -1), "下": (0, 1)}.get(键, (0, 0))
        我[0], 我[1] = min(宽 - 1, max(0, 我[0] + dx)), min(高 - 1, max(0, 我[1] + dy))
        if 键 == "空格":
            if abs(我[0] - 它[0]) <= 1 and abs(我[1] - 它[1]) <= 1:
                s["扑到"] += 1
                _说(s, 扑到了)
                s["它"] = list(随便哪())
            else:
                s["扑空"] += 1
                _说(s, 扑空了)
        elif random.random() < 猎物多快:
            近 = abs(我[0] - 它[0]) + abs(我[1] - 它[1]) < 4
            if 近 and random.random() < 0.7:  # 离得近就往外逃
                ex = (它[0] > 我[0]) - (它[0] < 我[0]) or random.choice((-1, 1))
                ey = (它[1] > 我[1]) - (它[1] < 我[1]) or random.choice((-1, 1))
            else:
                ex, ey = random.choice((-1, 0, 1)), random.choice((-1, 0, 1))
            它[0], 它[1] = min(宽 - 1, max(0, 它[0] + ex)), min(高 - 1, max(0, 它[1] + ey))
        s["时间"] += 1
        if s["时间"] >= 时长:
            _说(s, 结束, 99)
        return s

    def draw(s):
        行们 = [[""] * 宽 for _ in range(高)]
        行们[s["它"][1]][s["它"][0]] = 猎物
        行们[s["我"][1]][s["我"][0]] = 主角
        return _框(标题, 行们, 宽, w, _底下(s, f"{分数叫} {s['扑到']}  扑空 {s['扑空']}"))

    def over(s):
        return s["时间"] >= 时长

    return start, step, draw, over


# ── 打地鼠 ────────────────────────────────────────────

def 打地鼠(标题="打地鼠", 地鼠="m", 洞="o", 冒多少=0.25, 待多久=6, 时长=200,
        分数叫="拍到", 拍到了="啪！", 拍空了="空的……", 跑掉了="跑了", 结束="手酸了"):
    地鼠, 洞 = _一(地鼠), _一(洞)
    w = max(_宽(地鼠), _宽(洞))

    def start():
        return {"在": [0] * 9, "选": 4, "拍到": 0, "跑掉": 0, "时间": 0}

    def step(s, 键):
        r, c = divmod(s["选"], 3)
        r = max(0, min(2, r + {"上": -1, "下": 1}.get(键, 0)))
        c = max(0, min(2, c + {"左": -1, "右": 1}.get(键, 0)))
        s["选"] = r * 3 + c
        if 键 == "空格":
            if s["在"][s["选"]]:
                s["在"][s["选"]] = 0
                s["拍到"] += 1
                _说(s, 拍到了)
            else:
                _说(s, 拍空了)
        for i in range(9):
            if s["在"][i]:
                s["在"][i] -= 1
                if not s["在"][i]:
                    s["跑掉"] += 1
                    _说(s, 跑掉了, 3)
        if random.random() < 冒多少:
            空洞 = [i for i in range(9) if not s["在"][i]]
            if 空洞:
                s["在"][random.choice(空洞)] = 待多久
        s["时间"] += 1
        if s["时间"] >= 时长:
            _说(s, 结束, 99)
        return s

    def draw(s):
        lines = [f" {标题}"[:40], ""]
        for r in range(3):
            row = "   "
            for c in range(3):
                i = r * 3 + c
                里面 = _格(地鼠 if s["在"][i] else 洞, w)
                row += (f"[{里面}]" if i == s["选"] else f" {里面} ") + "    "
            lines += [row, ""]
        lines.append(_底下(s, f"{分数叫} {s['拍到']}  {跑掉了} {s['跑掉']}  还剩 {max(0, 时长 - s['时间'])}"))
        return "\n".join(lines)

    def over(s):
        return s["时间"] >= 时长

    return start, step, draw, over


# ── 跳 ────────────────────────────────────────────────

def 跳(标题="跳", 主角="A", 障碍="#", 宝贝="*", 宽=30, 高=7, 障碍多少=0.1, 宝贝多少=0.05, 命=3, 跳多高=3,
      终点=400, 分数叫="跑了", 宝贝叫="捡到", 撞了="绊倒了！", 捡到了="叼到了！", 结束="跑到了！"):
    主角, 障碍, 宝贝 = _一(主角), _一(障碍), _一(宝贝)
    w = max(_宽(主角), _宽(障碍), _宽(宝贝))
    宽, 高 = _场地(宽, 高, w, 最高=10)
    高 = max(高, 跳多高 + 2)
    我在 = 3  # 我在第几列

    def start():
        return {"地上": [""] * 宽, "天上": [""] * 宽, "空中": [], "命": 命, "走": 0, "宝": 0, "到了": False}

    def step(s, 键):
        if 键 in ("空格", "上") and not s["空中"]:
            s["空中"] = list(range(1, 跳多高 + 1)) + list(range(跳多高, 0, -1))
        elif s["空中"]:
            s["空中"].pop(0)
        s["走"] += 1
        近的 = s["地上"][-4:]
        新 = 障碍 if not any(近的) and random.random() < 障碍多少 else ""
        s["地上"] = s["地上"][1:] + [新]
        s["天上"] = s["天上"][1:] + [宝贝 if random.random() < 宝贝多少 else ""]
        多高 = s["空中"][0] if s["空中"] else 0
        if s["地上"][我在] and 多高 == 0:
            s["命"] -= 1
            s["地上"][我在] = ""
            _说(s, 撞了)
        if s["天上"][我在] and 多高 == 2:
            s["宝"] += 1
            s["天上"][我在] = ""
            _说(s, 捡到了)
        if 终点 and s["走"] >= 终点:
            s["到了"] = True
            _说(s, 结束, 99)
        return s

    def draw(s):
        行们 = [[""] * 宽 for _ in range(高)]
        行们[高 - 1] = list(s["地上"])
        for x, c in enumerate(s["天上"]):
            if c:
                行们[高 - 3][x] = c
        多高 = s["空中"][0] if s["空中"] else 0
        行们[高 - 1 - 多高][我在] = 主角
        return _框(标题, 行们, 宽, w, _底下(s, f"{分数叫} {s['走']}  {宝贝叫} {s['宝']}  命 {s['命']}"))

    def over(s):
        return s["命"] <= 0 or s["到了"]

    return start, step, draw, over
